    private function withMysqlEngine(string $statement): string
    {
        if (!str_starts_with(strtoupper(ltrim($statement)), 'CREATE TABLE')) {
            return $statement;
        }

        if (stripos($statement, 'ENGINE=') !== false) {
            return $statement;
        }

        return rtrim($statement) . ' ENGINE=InnoDB';
    }

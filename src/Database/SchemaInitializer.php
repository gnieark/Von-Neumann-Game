                crafted_at $nullableText,
                fabricator $nullableText,
                capacity_bonus $decimal NOT NULL DEFAULT 0,
                restored_detached_container_source_uid $nullableText,
                audit_metadata_json TEXT NOT NULL,
                created_at $text NOT NULL,
                updated_at $text NOT NULL,
                FOREIGN KEY(probe_id) REFERENCES neumann_probes(id)
            )",
            "CREATE INDEX IF NOT EXISTS idx_probe_items_probe_id ON probe_items(probe_id)",
            "CREATE INDEX IF NOT EXISTS idx_probe_items_uid ON probe_items(uid)",
            "CREATE INDEX IF NOT EXISTS idx_probe_items_restored_source ON probe_items(probe_id, restored_detached_container_source_uid)",
            "CREATE INDEX IF NOT EXISTS idx_probe_items_storage_container_id ON probe_items(storage_container_id)",
            "CREATE TABLE IF NOT EXISTS probe_improvement_blueprints (
                id $id,
